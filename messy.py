NAME_INDEX = 0
SUBJECT_COUNT = 3

students = [
    ["Rahul", 78, 88, 92],
    ["Priya", 65, 71, 69],
    ["Amit", 90, 94, 85],
    ["Sneha", 55, 60, 58],
    ["Vikram", 82, 79, 88]
]


def sum_scores(student_row):
    """Sum numeric scores in a student row, skipping the name at index 0."""
    total = 0
    for score_index in range(1, len(student_row)):
        total = total + student_row[score_index]
    return total


def average_score(student_row):
    """Return the average of a student's subject scores."""
    return sum_scores(student_row) / SUBJECT_COUNT


def count_above_class_average(student_rows):
    """Return how many students scored above the class average."""
    class_avg_total = 0
    for student_row in student_rows:
        class_avg_total = class_avg_total + average_score(student_row)
    class_avg = class_avg_total / len(student_rows)

    above_count = 0
    for student_row in student_rows:
        if average_score(student_row) > class_avg:
            above_count = above_count + 1
    return above_count


print("REPORT")

for student_row in students:
    total = sum_scores(student_row)
    average = average_score(student_row)

    if average >= 90:
        grade = "A"
    elif average >= 80:
        grade = "B"
    elif average >= 70:
        grade = "C"
    elif average >= 60:
        grade = "D"
    else:
        grade = "F"

    print(f"{student_row[NAME_INDEX]}{total}{average}{grade}")

class_average_total = 0

for student_row in students:
    average = average_score(student_row)
    class_average_total = class_average_total + average

print(f"Class average:{class_average_total / len(students)}")
print(f"Above class average:{count_above_class_average(students)}")

highest_average = 0
topper_name = ""

for student_row in students:
    average = average_score(student_row)

    if average > highest_average:
        highest_average = average
        topper_name = student_row[NAME_INDEX]

print(f"Topper:{topper_name}{highest_average}")
